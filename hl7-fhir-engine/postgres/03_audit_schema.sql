-- ============================================================
-- Audit schema — persistent records of FHIR exchanges and
-- security events. Lives alongside the legacy SIL schema in
-- the same Postgres instance.
--
-- Retention policy:
--   exchange_log.payload_json / response_json → purged after 90 days
--   exchange_log row itself                    → kept indefinitely (small)
--   security_event                             → kept indefinitely
--
-- Append-only: the middleware connects as audit_writer, which may only
-- SELECT and INSERT these two tables (07_roles.sql). A synchronisation
-- writes an 'intent' row BEFORE any data is sent to HAPI (fail-closed)
-- and an 'outcome' row afterwards, instead of updating one row.
-- Row identifiers are generated by the middleware, so events replayed
-- from the local outbox are inserted at most once (ON CONFLICT DO NOTHING).
-- ============================================================

CREATE SCHEMA IF NOT EXISTS audit;

-- One row per FHIR exchange (sync_order, sync_all, bundle_post)
CREATE TABLE IF NOT EXISTS audit.exchange_log (
    exchange_id     UUID         PRIMARY KEY DEFAULT gen_random_uuid(),
    occurred_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    user_sub        VARCHAR(64),
    user_name       VARCHAR(120),
    role            VARCHAR(20),
    phase           VARCHAR(10)  NOT NULL DEFAULT 'outcome'
                    CHECK (phase IN ('intent', 'outcome')),
    correlation_id  UUID,                    -- outcome rows: exchange_id of their intent row
    operation       VARCHAR(40)  NOT NULL,   -- sync_order | bundle_post | bundle_ingest | oru_ingest
    order_id        VARCHAR(64),
    bundle_id       VARCHAR(64),
    resource_count  INTEGER,
    status          VARCHAR(10)  NOT NULL,   -- pending (intent) | ok | error
    error_message   TEXT,
    payload_json    JSONB,                   -- the FHIR Bundle sent
    response_json   JSONB,                   -- HAPI's reply
    payload_purged  BOOLEAN      NOT NULL DEFAULT false
);

CREATE INDEX IF NOT EXISTS ix_exchange_log_occurred ON audit.exchange_log(occurred_at DESC);
CREATE INDEX IF NOT EXISTS ix_exchange_log_user     ON audit.exchange_log(user_sub);
CREATE INDEX IF NOT EXISTS ix_exchange_log_order    ON audit.exchange_log(order_id);
CREATE INDEX IF NOT EXISTS ix_exchange_log_status   ON audit.exchange_log(status);
CREATE INDEX IF NOT EXISTS ix_exchange_log_corr     ON audit.exchange_log(correlation_id);

-- Persistent security audit trail (login, auth, RBAC denies, etc.)
CREATE TABLE IF NOT EXISTS audit.security_event (
    event_id      UUID         PRIMARY KEY DEFAULT gen_random_uuid(),
    occurred_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    level         VARCHAR(10)  NOT NULL,    -- AUTH | DENY | OK | ERROR | WARN | INFO
    user_sub      VARCHAR(64),
    message       TEXT         NOT NULL,
    ip_address    VARCHAR(45),
    method        VARCHAR(10),
    path          VARCHAR(255),
    status_code   INTEGER
);

CREATE INDEX IF NOT EXISTS ix_security_event_occurred ON audit.security_event(occurred_at DESC);
CREATE INDEX IF NOT EXISTS ix_security_event_level    ON audit.security_event(level);
CREATE INDEX IF NOT EXISTS ix_security_event_user     ON audit.security_event(user_sub);

-- One row per exchange: each intent with its outcome (or 'pending' if the
-- process stopped between the two), plus outcome rows that had no intent.
CREATE OR REPLACE VIEW audit.exchange_summary AS
SELECT i.exchange_id, i.occurred_at, i.user_sub, i.user_name, i.role, i.operation, i.order_id,
       COALESCE(o.bundle_id, i.bundle_id)           AS bundle_id,
       COALESCE(o.resource_count, i.resource_count) AS resource_count,
       COALESCE(o.status, 'pending')                AS status,
       o.error_message,
       o.occurred_at                                AS completed_at,
       i.payload_purged
  FROM audit.exchange_log i
  LEFT JOIN audit.exchange_log o ON o.correlation_id = i.exchange_id AND o.phase = 'outcome'
 WHERE i.phase = 'intent'
UNION ALL
SELECT exchange_id, occurred_at, user_sub, user_name, role, operation, order_id, bundle_id,
       resource_count, status, error_message, occurred_at, payload_purged
  FROM audit.exchange_log
 WHERE phase = 'outcome' AND correlation_id IS NULL;

-- 90-day retention helper — call periodically to nullify old payloads
-- without losing the exchange metadata. SECURITY DEFINER: it runs with
-- the owner's rights, so audit_writer can purge payloads without holding
-- UPDATE on the table (07_roles.sql grants EXECUTE only).
CREATE OR REPLACE FUNCTION audit.purge_old_payloads() RETURNS INTEGER
    SECURITY DEFINER SET search_path = audit, pg_temp AS $$
DECLARE
    affected INTEGER;
BEGIN
    UPDATE audit.exchange_log
       SET payload_json = NULL,
           response_json = NULL,
           payload_purged = true
     WHERE occurred_at < now() - INTERVAL '90 days'
       AND payload_purged = false;
    GET DIAGNOSTICS affected = ROW_COUNT;
    RETURN affected;
END;
$$ LANGUAGE plpgsql;
